<?php

namespace App\Services\Export;

use Spatie\Browsershot\Browsershot;
use Throwable;

class DocumentPdfRenderer
{
    /**
     * @throws PdfRenderingException when headless Chrome cannot start, times out, or fails to print.
     */
    public function render(string $html): string
    {
        try {
            $browsershot = Browsershot::html($html)
                ->format('A4')
                ->showBackground()
                ->margins(15, 12, 18, 12)
                ->disableJavascript()
                // /dev/shm is tiny on small VPSs; GPU is useless for headless printing.
                ->addChromiumArguments(['disable-dev-shm-usage', 'disable-gpu'])
                ->setNodeModulePath((string) config('pdf.node_modules_path'))
                ->timeout((int) config('pdf.timeout', 60));

            // Needed when the OS blocks unprivileged user namespaces (e.g. Ubuntu 24.04 AppArmor).
            // Acceptable here: JavaScript is disabled and the HTML is generated by this app.
            if (config('pdf.no_sandbox')) {
                $browsershot->noSandbox();
            }

            if ($path = config('pdf.chrome_path')) {
                $browsershot->setChromePath($path);
            }

            if ($node = config('pdf.node_binary')) {
                $browsershot->setNodeBinary($node);
            }

            if ($npm = config('pdf.npm_binary')) {
                $browsershot->setNpmBinary($npm);
            }

            return $browsershot->pdf();
        } catch (Throwable $e) {
            throw new PdfRenderingException(
                'The PDF engine (headless Chrome) failed: '.$e->getMessage(),
                previous: $e,
            );
        }
    }

    /**
     * @font-face rules for the bundled Arabic font (resources/fonts, SIL OFL), inlined as data URIs
     * so PDF output never depends on fonts installed on the server's OS.
     */
    public function fontCss(): string
    {
        static $css = null;

        if ($css !== null) {
            return $css;
        }

        $range = 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0897-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC';

        $css = '';
        foreach ([400, 700] as $weight) {
            $path = resource_path("fonts/noto-naskh-arabic-arabic-{$weight}-normal.woff2");

            if (! is_file($path)) {
                continue;
            }

            $data = base64_encode((string) file_get_contents($path));
            $css .= "@font-face{font-family:'Noto Naskh Arabic';font-style:normal;font-weight:{$weight};"
                ."src:url(data:font/woff2;base64,{$data}) format('woff2');unicode-range:{$range};}
";
        }

        return $css;
    }

    /**
     * The app's compiled Tailwind CSS, inlined so the PDF page needs no network access.
     * Returns '' when no production build exists yet.
     */
    public function appCss(): string
    {
        $manifestPath = public_path('build/manifest.json');

        if (! is_file($manifestPath)) {
            return '';
        }

        $manifest = json_decode((string) file_get_contents($manifestPath), true);
        $files = $manifest['resources/js/app.tsx']['css'] ?? [];

        return collect($files)
            ->map(fn (string $file) => public_path('build/'.$file))
            ->filter(fn (string $path) => is_file($path))
            ->map(fn (string $path) => (string) file_get_contents($path))
            ->implode("\n");
    }
}
